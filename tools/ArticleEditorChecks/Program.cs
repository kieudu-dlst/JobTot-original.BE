using (var scope = app.Services.CreateScope())
{
    var db = scope.ServiceProvider.GetRequiredService<RecruitmentDbContext>();
    var account = new Account { AccountType = "Admin", AccountStatus = "Active", FullName = "Admin fixture", PasswordHash = "test-only-password-stamp" };
    var session = new CandidateRefreshSession
    {
        AccountId = account.Id, PasswordStamp = AdminAuthentication.Stamp(account.PasswordHash),
        TokenHash = Guid.NewGuid().ToString(), ExpiresAt = DateTimeOffset.UtcNow.AddHours(1),
    };
    db.AddRange(account, session);
    await db.SaveChangesAsync();
    admin.DefaultRequestHeaders.Authorization = new AuthenticationHeaderValue("Bearer", AdminAuthentication.Issue(
        scope.ServiceProvider.GetRequiredService<CandidateJwtSettings>(), account.Id, session.Id, account.FullName, session.ExpiresAt));
