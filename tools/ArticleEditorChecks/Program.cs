var checks = new List<string>();
void Check(bool condition, string name)
{
    if (!condition) throw new InvalidOperationException(name);
    checks.Add(name);
    Console.WriteLine($"PASS {name}");
}
async Task<JsonElement> Json(HttpResponseMessage response)
{
    var body = await response.Content.ReadAsStringAsync();
    Check(response.IsSuccessStatusCode, $"{response.RequestMessage!.Method} {response.RequestMessage.RequestUri!.AbsolutePath} succeeds");
    return JsonSerializer.Deserialize<JsonElement>(body);
}
object Input(string body, bool published, Guid? version = null) => new
{
    title = "Bài kiểm tra trực quan", category = "Cẩm nang", summary = "Nội dung kiểm thử",
    content = body, published, version,
};
Check(content.Contains("colwidth=\"200\"") && content.Contains("Nội dung ô"), "Uses resized table content generated by the frontend editor");
var created = await Json(await admin.PostAsJsonAsync("/api/admin/career-articles", Input(content, false)));
var id = created.GetProperty("id").GetGuid();
Check(created.GetProperty("content").GetString() == content, "Create preserves visual table content and column widths exactly");
Check((await visitor.GetAsync($"/api/career-articles/{id}")).StatusCode == HttpStatusCode.NotFound, "Draft remains hidden from visitors");
var list = await Json(await admin.GetAsync("/api/admin/career-articles"));
var reopened = list.EnumerateArray().Single(a => a.GetProperty("id").GetGuid() == id);
Check(reopened.GetProperty("content").GetString() == content, "Admin reopen retrieves the complete saved editor content");
var updated = content.Replace("Nội dung ô", "Ô đã chỉnh sửa");
var published = await Json(await admin.PutAsJsonAsync($"/api/admin/career-articles/{id}", Input(updated, true, reopened.GetProperty("version").GetGuid())));
var publicArticle = await Json(await visitor.GetAsync($"/api/career-articles/{id}"));
Check(publicArticle.GetProperty("content").GetString() == updated, "Published article returns the same updated table and persisted widths");
Check((await admin.PutAsJsonAsync($"/api/admin/career-articles/{id}", Input(content, true, created.GetProperty("version").GetGuid()))).StatusCode
    == HttpStatusCode.Conflict, "Existing concurrent-update protection remains active");
const string legacy = "## Bài cũ\n\n| Kỹ năng | Mức độ |\n| --- | --- |\n| React | Tốt |";
var old = await Json(await admin.PostAsJsonAsync("/api/admin/career-articles", Input(legacy, true)));
var oldId = old.GetProperty("id").GetGuid();
Check((await Json(await visitor.GetAsync($"/api/career-articles/{oldId}"))).GetProperty("content").GetString() == legacy,
    "Legacy Markdown table remains readable without migration or resaving");
Check((await visitor.PutAsJsonAsync($"/api/admin/career-articles/{id}", Input(content, true))).StatusCode == HttpStatusCode.Unauthorized,
    "Anonymous visitors cannot edit articles");
await File.WriteAllTextAsync(Path.Combine(output, "api-public-article.json"), publicArticle.GetRawText());
